// Honest reading time from the actual word count (~200 wpm), so the label
// always matches the article instead of a hand-set guess.
export function readTime(post) {
  if (!post || !Array.isArray(post.body)) return 1;
  const words = post.body.reduce((n, b) => {
    const text = b.t === "ul" ? (b.items || []).join(" ") : (b.c || "");
    return n + text.trim().split(/\s+/).filter(Boolean).length;
  }, 0);
  return Math.max(1, Math.round(words / 200));
}
